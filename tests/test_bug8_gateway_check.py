"""
tests/test_bug8_gateway_check.py — Unit Tests for BUG-8:
1. Token masking: never leak full tokens, mask safely (e.g. fre...8b4f)
2. Exit code 2 when token is missing/empty
3. Fallback logic: mock 429 on primary model -> successful generation on fallback model
"""

from __future__ import annotations

import logging
from pathlib import Path
from unittest.mock import MagicMock, patch
import pytest

from scripts.check_llm_gateway import mask_token, main as check_gateway_main
from freellmapi_client import FreeLLMClient


def test_token_masking():
    # 1. Standard long token
    raw_token = "freellmapi-ceb04983702628b4439a5a1d9e9bf34484f948c29dbe8b4f"
    masked = mask_token(raw_token)
    assert masked == "fre...8b4f"
    assert raw_token not in masked
    assert len(masked) < len(raw_token)

    # 2. OpenAI-style key
    raw_key = "sk-proj-1234567890abcdef"
    masked_key = mask_token(raw_key)
    assert masked_key == "sk-...cdef"
    assert raw_key not in masked_key

    # 3. Empty or short token
    assert mask_token("") == "<MISSING>"
    assert mask_token("   ") == "<MISSING>"
    assert mask_token("abcdef") == "ab...ef"


def test_exit_code_2_when_token_missing(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    empty_env = tmp_path / "empty.env"
    empty_env.write_text("# No token here\n", encoding="utf-8")

    monkeypatch.setenv("FREELLMAPI_TOKEN", "")
    monkeypatch.setenv("FREELLMAPI_KEY", "")
    monkeypatch.setattr("sys.argv", ["check_llm_gateway.py", "--env-file", str(empty_env)])

    exit_code = check_gateway_main()
    assert exit_code == 2


def test_fallback_logic_429_to_success(monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture):
    client = FreeLLMClient(api_key="test-mock-token")
    client.enabled = True
    client.default_model = "primary-model"
    client.fallback_models = ["fallback-model-1", "fallback-model-2"]
    client.edge_url = "https://mock-edge.test"
    client.local_url = ""
    client.api_url = ""

    class MockResponse:
        def __init__(self, status_code: int, data: dict | None = None):
            self.status_code = status_code
            self._data = data or {}
            self.text = "Mocked Response"

        def json(self):
            return self._data

    def mock_post(url, *args, **kwargs):
        payload = kwargs.get("json", {})
        req_model = payload.get("model", "")
        if req_model == "primary-model":
            # Primary model fails with rate limit 429
            return MockResponse(status_code=429)
        elif req_model == "fallback-model-1":
            # Fallback model succeeds
            return MockResponse(
                status_code=200,
                data={
                    "choices": [
                        {
                            "message": {
                                "content": "Comprehensive financial guide generated by fallback model."
                            }
                        }
                    ]
                },
            )
        return MockResponse(status_code=500)

    # Patch ensure_local_daemon_running to False so it relies on mocked post
    monkeypatch.setattr("freellmapi_client.ensure_local_daemon_running", lambda key: False)

    with patch("httpx.Client.post", side_effect=mock_post):
        with caplog.at_level(logging.WARNING):
            result = client.generate_completion(
                prompt="Write loan guide",
                system_prompt="You are a financial writer.",
                model="primary-model",
            )

    assert result == "Comprehensive financial guide generated by fallback model."
    # Verify explicit fallback log message
    assert any("switching to fallback model 'fallback-model-1'" in record.message for record in caplog.records)


def test_auto_model_resolves_to_first_fallback(monkeypatch: pytest.MonkeyPatch):
    """Verify model='auto' dispatches to config's first fallback model, not an unlisted default."""
    client = FreeLLMClient(api_key="test-token")
    client.enabled = True
    client.edge_url = "https://mock-edge.test"
    client.local_url = ""
    client.api_url = ""

    captured_models = []

    class MockResponse:
        def __init__(self):
            self.status_code = 200
            self.text = "OK"

        def json(self):
            return {"choices": [{"message": {"content": "Generated text"}}]}

    def mock_post(url, *args, **kwargs):
        payload = kwargs.get("json", {})
        captured_models.append(payload.get("model"))
        return MockResponse()

    monkeypatch.setattr("freellmapi_client.ensure_local_daemon_running", lambda key: False)

    with patch("httpx.Client.post", side_effect=mock_post):
        client.generate_completion(prompt="Hello", model="auto")

    assert len(captured_models) > 0
    expected_primary = client.fallback_models[0]
    assert captured_models[0] == expected_primary

